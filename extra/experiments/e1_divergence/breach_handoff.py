"""Emit the Breach handoff script for the E1 column.

Generates ``extra/other_tools/breach/generate_e1_column.m`` from the
spec/signal registries (single source of truth, so the Breach pairs cannot
drift from the other E1 columns) -- rerun and commit after any registry
change. The generated MATLAB writes one CSV per pair (plus ``breach_meta.txt``)
into ``cache/breach_column/``. The run itself happens on the MATLAB machine;
see ``extra/other_tools/breach/HANDOFF.md``.

Usage:
    uv run python extra/experiments/e1_divergence/breach_handoff.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT))

# ``aggregate`` is the single source of truth for the E1 pair set and the
# decision-point annotations (sibling module; this script's directory is on
# sys.path[0] when run directly).
from aggregate import ANNOTATIONS, SIGNALS, SPECS  # noqa: E402

OUT_M = REPO_ROOT / "extra" / "other_tools" / "breach" / "generate_e1_column.m"

_VAR_ORDER = ("x", "y", "z")


def _vec(values: list[float]) -> str:
    return "[" + " ".join(f"{v:g}" for v in values) + "]"


def _case_call(name: str, block: str, spec: dict[str, Any], signal: dict[str, Any]) -> list[str]:
    assert "breach" in spec
    values = signal["values"]
    var_names = [n for n in _VAR_ORDER if n in values]
    assert set(var_names) == set(values), f"{name}: variables must be x/y/z"
    args = ", ".join(_vec([float(v) for v in values[n]]) for n in var_names)
    helper = f"eval_{len(var_names)}sig"
    times = [float(t) for t in signal["times"]]
    lines = [f"    % [{block}] {name}: {spec['tidystl']}"]
    if block == "divergence":
        lines.append(f"    %   decision point: {_DECISION_POINT[name]}")
    lines.append(
        f"    n = n + {helper}(out, '{name}', ...\n"
        f"        {_vec(times)}, {args}, ...\n"
        f"        '{spec['breach']}');"
    )
    return lines


def emit() -> str:
    body: list[str] = []
    n_pairs = 0
    for spec_rel, signal_rel in zip(SPECS, SIGNALS, strict=True):
        spec_path = REPO_ROOT / spec_rel
        block = "divergence" if spec_path.stem.split("_")[-1] == "div" else "baseline"
        specs = json.loads(spec_path.read_text())
        signals = json.loads((REPO_ROOT / signal_rel).read_text())
        for name, spec in specs.items():
            if "breach" not in spec:
                continue
            body.extend(_case_call(name, block, spec, signals[name]))
            body.append("")
            n_pairs += 1

    case_block = "\n".join(body).rstrip()
    return f"""function generate_e1_column()
%GENERATE_E1_COLUMN  Real-Breach robustness for the RV 2026 E1 pair set.
%
%   AUTO-GENERATED by extra/experiments/e1_divergence/breach_handoff.py from
%   the spec/signal registries (extra/experiments/registry/) -- do not edit
%   by hand; rerun the emitter instead. See HANDOFF.md in this directory.
%
%   Requires Breach (github.com/decyphir/breach) on the MATLAB path,
%   initialized via InitBreach. Run from the tidystl repository root:
%
%     >> addpath('extra/other_tools/breach'); generate_e1_column
%
%   Writes one CSV per case plus breach_meta.txt to
%   extra/experiments/e1_divergence/cache/breach_column/

    out = fullfile(pwd, 'extra', 'experiments', 'e1_divergence', 'cache', 'breach_column');
    if ~exist(out, 'dir')
        mkdir(out);
    end

    fprintf('E1 Breach column -> %s\\n\\n', out);
    write_meta(out);
    n = 0;

{case_block}

    fprintf('\\nE1 Breach column: %d/{n_pairs} pairs OK\\n', n);
end


%% ==================== Helper functions ====================
%% (mirrors generate_ground_truth.m; duplicated so this file is
%%  self-contained)

function ok = eval_1sig(out, name, time, x, formula)
    try
        BrSys = BreachTraceSystem({{'x'}});
        traj = struct('time', time, 'X', x);
        BrSys.AddTrace(traj);
        save_rob(BrSys, name, formula, time, out);
        ok = 1;
    catch e
        fprintf('  [FAIL] %s: %s\\n', name, e.message);
        ok = 0;
    end
end

function ok = eval_2sig(out, name, time, x, y, formula)
    try
        BrSys = BreachTraceSystem({{'x', 'y'}});
        traj = struct('time', time, 'X', [x; y]);
        BrSys.AddTrace(traj);
        save_rob(BrSys, name, formula, time, out);
        ok = 1;
    catch e
        fprintf('  [FAIL] %s: %s\\n', name, e.message);
        ok = 0;
    end
end

function ok = eval_3sig(out, name, time, x, y, z, formula)
    try
        BrSys = BreachTraceSystem({{'x', 'y', 'z'}});
        traj = struct('time', time, 'X', [x; y; z]);
        BrSys.AddTrace(traj);
        save_rob(BrSys, name, formula, time, out);
        ok = 1;
    catch e
        fprintf('  [FAIL] %s: %s\\n', name, e.message);
        ok = 0;
    end
end

function save_rob(BrSys, name, formula, time, out)
    phi = STL_Formula(name, formula);
    [rob, tau] = STL_Eval(BrSys.Sys, phi, BrSys.P, BrSys.P.traj{{1}}, time);

    fpath = fullfile(out, [name '.csv']);
    fid = fopen(fpath, 'w');
    fprintf(fid, 'time,robustness\\n');
    for i = 1:length(tau)
        fprintf(fid, '%.15g,%.15g\\n', tau(i), rob(i));
    end
    fclose(fid);
    fprintf('  [OK] %s -> %d points\\n', name, length(tau));
end

function write_meta(out)
    fid = fopen(fullfile(out, 'breach_meta.txt'), 'w');
    fprintf(fid, 'date: %s\\n', datestr(now, 31));
    fprintf(fid, 'matlab: %s\\n', version);
    try
        breach_dir = fileparts(which('InitBreach'));
        fprintf(fid, 'breach_path: %s\\n', breach_dir);
        [st, rev] = system(['git -C "' breach_dir '" rev-parse HEAD']);
        if st == 0
            fprintf(fid, 'breach_commit: %s', rev);
        end
    catch
        fprintf(fid, 'breach_commit: (unavailable)\\n');
    end
    fclose(fid);
end
"""


def main() -> None:
    OUT_M.write_text(emit())
    print(f"wrote {OUT_M}")


# Decision-point text (full name) for the divergence-block comments,
# from the annotations; only div-block names print it.
_DECISION_POINT: dict[str, str] = {name: entry[0] for name, entry in ANNOTATIONS.items()}


if __name__ == "__main__":
    main()
